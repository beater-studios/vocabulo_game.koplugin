package.path = "./?.lua;" .. package.path
local Engine = require("vocabulo_game/engine")

local passed, failed = 0, 0
local function test(name, fn)
    local ok, err = pcall(fn)
    if ok then
        passed = passed + 1
    else
        failed = failed + 1
        print("FALHOU: " .. name .. "\n  " .. tostring(err))
    end
end
local function eq(actual, expected)
    if actual ~= expected then
        error(string.format("esperado %s, veio %s", tostring(expected), tostring(actual)), 2)
    end
end
local function marks(guess, answer)
    local out = {}
    for i, state in ipairs(Engine.evaluate(guess, answer)) do
        out[i] = state:sub(1, 1)
    end
    return table.concat(out)
end
local function game(answer, lang)
    return Engine.new{ lang = lang or "pt", length = #Engine.split(Engine.plain(answer, lang or "pt")), day = 10, answer = answer, is_valid = function(word) return word ~= "zzzzz" end }
end
local function type_word(g, word)
    for _, letter in ipairs(Engine.split(word)) do g:add_letter(letter) end
end

test("avaliação simples", function()
    eq(marks("carro", "carro"), "ccccc")
    eq(marks("mundo", "carro"), "aaaac")
    eq(marks("litro", "carro"), "aaacc")
end)
test("letra repetida só marca as que existem", function()
    eq(marks("arara", "carro"), "ppaca")
    eq(marks("eeeee", "pedra"), "acaaa")
    eq(marks("allee", "apple"), "cpaac")
end)
test("letra certa na posição tem prioridade sobre a presente", function()
    eq(marks("abbey", "babes"), "ppcca")
    eq(marks("speed", "abide"), "aapap")
    eq(marks("erase", "speed"), "paapp")
end)
test("normaliza acentos e cedilha", function()
    eq(Engine.plain("ação", "pt"), "acao")
    eq(Engine.plain("família", "pt"), "familia")
    eq(Engine.plain("músicas", "es"), "musicas")
end)
test("espanhol mantém o ñ como letra própria", function()
    eq(Engine.plain("niño", "es"), "niño")
    eq(Engine.plain("mañana", "es"), "mañana")
    eq(#Engine.split("niño"), 4)
    eq(marks("nino", "niño"), "ccac")
end)
test("mesma data dá o mesmo dia, e dias seguidos somam um", function()
    eq(Engine.day_number{ year = 2026, month = 1, day = 1 }, 0)
    eq(Engine.day_number{ year = 2026, month = 1, day = 2 }, 1)
    eq(Engine.day_number{ year = 2026, month = 3, day = 1 }, 59)
    eq(Engine.day_number{ year = 2027, month = 1, day = 1 }, 365)
    eq(Engine.day_number{ year = 2028, month = 3, day = 1 }, 790)
end)
test("sequência de respostas dá a volta na lista", function()
    local answers = { "a", "b", "c" }
    eq(Engine.answer_for_day(answers, 0), "a")
    eq(Engine.answer_for_day(answers, 2), "c")
    eq(Engine.answer_for_day(answers, 3), "a")
    eq(Engine.answer_for_day(answers, 310), "b")
end)
test("não aceita palavra curta nem desconhecida", function()
    local g = game("carro")
    type_word(g, "car")
    local ok, why = g:submit()
    eq(ok, false); eq(why, "short")
    for _ = 1, 3 do g:remove_letter() end
    type_word(g, "zzzzz")
    ok, why = g:submit()
    eq(ok, false); eq(why, "unknown")
    eq(#g.guesses, 0)
end)
test("não passa do tamanho e apaga letra", function()
    local g = game("carro")
    type_word(g, "abcdefg")
    eq(#g.current, 5)
    g:remove_letter()
    eq(#g.current, 4)
end)
test("resposta com acento ganha digitando sem acento", function()
    local g = game("ação")
    type_word(g, "acao")
    eq(g:submit(), true)
    eq(g:is_won(), true)
    eq(g:is_over(), true)
    eq(g:add_letter("a"), false)
end)
test("acaba depois de seis tentativas", function()
    local g = game("carro")
    for _ = 1, Engine.ATTEMPTS do
        type_word(g, "mundo")
        eq(g:submit(), true)
    end
    eq(g:is_won(), false)
    eq(g:is_over(), true)
    type_word(g, "mundo")
    local ok, why = g:submit()
    eq(ok, false); eq(why, "over")
end)
test("salvar e restaurar recalcula os resultados", function()
    local g = game("carro")
    type_word(g, "mundo"); g:submit()
    local saved = g:serialize()
    local other = game("carro")
    other:restore(saved)
    eq(#other.results, 1)
    eq(other.day, saved.day)
    eq(saved.answer, "carro")
    eq(other.results[1][5], Engine.evaluate("mundo", "carro")[5])
end)
test("teclado guarda o melhor estado de cada letra", function()
    local g = game("carro")
    type_word(g, "rumor"); g:submit()
    type_word(g, "curto"); g:submit()
    local states = g:keyboard_states()
    eq(states.c, Engine.CORRECT)
    eq(states.u, Engine.ABSENT)
    eq(states.r, Engine.CORRECT)
end)
test("sequência de vitórias", function()
    local s = Engine.new_stats()
    Engine.record_result(s, 10, true, 3)
    Engine.record_result(s, 11, true, 4)
    eq(s.streak, 2); eq(s.best_streak, 2); eq(s.played, 2)
    Engine.record_result(s, 11, true, 2)
    eq(s.played, 2)
    Engine.record_result(s, 13, true, 2)
    eq(s.streak, 1); eq(s.best_streak, 2)
    Engine.record_result(s, 14, false)
    eq(s.streak, 0); eq(s.won, 3); eq(s.distribution[2], 1)
end)
test("sequência mostrada zera depois de um dia sem jogar", function()
    local s = Engine.new_stats()
    eq(Engine.current_streak(s, 10), 0)
    Engine.record_result(s, 10, true, 3)
    Engine.record_result(s, 11, true, 3)
    eq(Engine.current_streak(s, 11), 2)
    eq(Engine.current_streak(s, 12), 2)
    eq(Engine.current_streak(s, 13), 0)
    eq(s.streak, 2)
end)
test("resultado compartilhado não revela letras", function()
    local g = game("carro")
    type_word(g, "mundo"); g:submit()
    type_word(g, "carro"); g:submit()
    local text = g:share_text("Jogo")
    eq(text:find("mundo", 1, true), nil)
    eq(text:find("carro", 1, true), nil)
    eq(text:find("PT 5 #10 2/6", 1, true) ~= nil, true)
end)

test("modo livre evita as palavras recentes", function()
    local answers = { "ação", "bolo", "casa" }
    local first = function() return 1 end
    eq(Engine.pick_free(answers, "pt", {}, first), "ação")
    eq(Engine.pick_free(answers, "pt", { acao = true }, first), "bolo")
    eq(Engine.pick_free(answers, "pt", { acao = true, bolo = true }, first), "casa")
end)
test("modo livre evita a palavra de hoje e as dos próximos dias", function()
    local answers = { "ação", "bolo", "casa", "dado", "eixo" }
    local avoided = Engine.free_avoided(answers, "pt", 4, 2, { "bolo" })
    eq(avoided.eixo, true)
    eq(avoided.acao, true)
    eq(avoided.bolo, true)
    eq(avoided.casa, nil)
    eq(avoided.dado, nil)
end)
test("modo livre ainda sorteia quando todas são recentes", function()
    local answers = { "bolo", "casa" }
    local last = function(n) return n end
    eq(Engine.pick_free(answers, "pt", { bolo = true, casa = true }, last), "casa")
end)
test("modo livre usa o sorteio recebido", function()
    local answers = { "bolo", "casa", "dado" }
    eq(Engine.pick_free(answers, "pt", { casa = true }, function(n) eq(n, 2); return 2 end), "dado")
end)
test("maiúsculas com acento", function()
    eq(Engine.upper("ã"), "Ã")
    eq(Engine.upper("ñ"), "Ñ")
    eq(Engine.upper("ç"), "Ç")
    eq(Engine.upper("a"), "A")
end)

print(string.format("%d passaram, %d falharam", passed, failed))
os.exit(failed == 0 and 0 or 1)
